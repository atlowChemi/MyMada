const MEDICAL_CODE_SECTIONS_ORDER = ['AREA', 'TRAUMA', 'PAIN', 'CARDIO_VASCULAR', 'RESPIRATORY', 'NEUROLOGY', 'GASTRO', 'INFECTION', 'PSYCHIATRY', 'ENDOCRINOLOGY', 'UROLOGY', 'GENERAL'] as const;

interface MedicalCodeItem {
    code: string;
    name: string;
    section: keyof typeof MEDICAL_CODES;
    type: 'item';
}
interface MedicalCodeTitle {
    title: string;
    section: keyof typeof MEDICAL_CODES;
    type: 'title';
}

export type MedicalCodeEl = MedicalCodeItem | MedicalCodeTitle;

export const getMedicalCodeItems = (query: string) => {
    return MEDICAL_CODE_SECTIONS_ORDER.flatMap(section => {
        const sectionItems = Object.entries(MEDICAL_CODES[section])
            .filter(([code, name]) => name.includes(query) || code.includes(query))
            .map<MedicalCodeEl>(([code, name]) => ({ type: 'item', code, name, section }));

        if (sectionItems.length) {
            sectionItems.unshift({ type: 'title', section, title: MEDICAL_CODE_SECTION_TITLE[section] });
        }
        return sectionItems;
    });
};
